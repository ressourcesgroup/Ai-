"""Script-centric generators: remotes, leaderstats, DataStore, HUD, NPC patrol, door, platform.

Luau templates use ``{{KEY}}`` placeholders filled by :func:`fill`. All are
server-authoritative: the client only *requests*; the server validates.
"""

from __future__ import annotations

import math
import re

from .base import (ToolOutput, c3, create_instances, create_script, enum, lua_string, node, part, safe_identifier,
                   udim, udim2, v2, v3)

HEADER = "-- Generated by GODMODE {tool} (deterministic template, verified by godmode.luau; not neural-model output)\n"


def fill(template: str, **kw) -> str:
    out = template
    for k, v in kw.items():
        out = out.replace("{{" + k + "}}", str(v))
    leftover = re.search(r"\{\{[A-Z_]+\}\}", out)
    if leftover:
        raise ValueError(f"unfilled placeholder {leftover.group(0)}")
    return out


# ------------------------------------------------------------------ RemoteEvent system

REMOTE_SERVER = """{{HEADER}}-- Server side of the {{NAME}} RemoteEvent. The client only REQUESTS an action;
-- every argument is type-checked, range-checked and rate limited here.
local Players = game:GetService("Players")
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local REMOTE_NAME = {{NAME_STR}}
local MAX_CALLS_PER_WINDOW = 8
local WINDOW_SECONDS = 1
local MAX_AMOUNT = 100
local ALLOWED_ACTIONS = {
	Use = true,
	Interact = true,
	Emote = true,
}

local remotesFolder = ReplicatedStorage:FindFirstChild("Remotes")
if not remotesFolder then
	remotesFolder = Instance.new("Folder")
	remotesFolder.Name = "Remotes"
	remotesFolder.Parent = ReplicatedStorage
end

local remote = remotesFolder:FindFirstChild(REMOTE_NAME)
if not remote then
	remote = Instance.new("RemoteEvent")
	remote.Name = REMOTE_NAME
	remote.Parent = remotesFolder
end

local callLog = {}

local function isRateLimited(player: Player): boolean
	local now = os.clock()
	local entry = callLog[player]
	if entry == nil or now - entry.windowStart >= WINDOW_SECONDS then
		callLog[player] = { count = 1, windowStart = now }
		return false
	end
	entry.count += 1
	return entry.count > MAX_CALLS_PER_WINDOW
end

local function handleAction(player: Player, action: string, amount: number)
	-- Server-authoritative game logic goes here. Never trust the client for
	-- damage, currency or positions: recompute them from server state.
	print(("%s requested %s x%d"):format(player.Name, action, amount))
end

remote.OnServerEvent:Connect(function(player: Player, action: unknown, amount: unknown)
	if isRateLimited(player) then
		return
	end
	if typeof(action) ~= "string" or #action > 32 or ALLOWED_ACTIONS[action] ~= true then
		return
	end
	if typeof(amount) ~= "number" or amount ~= amount or amount < 1 or amount > MAX_AMOUNT then
		return
	end
	local character = player.Character
	local humanoid = character and character:FindFirstChildOfClass("Humanoid")
	if humanoid == nil or humanoid.Health <= 0 then
		return
	end
	handleAction(player, action, math.floor(amount))
end)

Players.PlayerRemoving:Connect(function(player: Player)
	callLog[player] = nil
end)
"""

REMOTE_CLIENT = """{{HEADER}}-- Client side of the {{NAME}} RemoteEvent: sends a request, the server decides.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ContextActionService = game:GetService("ContextActionService")

local remote = ReplicatedStorage:WaitForChild("Remotes"):WaitForChild({{NAME_STR}})
local CLIENT_COOLDOWN = 0.25
local lastFire = 0

local function request(action: string, amount: number)
	local now = os.clock()
	if now - lastFire < CLIENT_COOLDOWN then
		return
	end
	lastFire = now
	remote:FireServer(action, amount)
end

ContextActionService:BindAction("Godmode{{NAME}}Use", function(_, inputState)
	if inputState == Enum.UserInputState.Begin then
		request("Use", 1)
	end
	return Enum.ContextActionResult.Pass
end, false, Enum.KeyCode.E)
"""


def remote_event(params: dict, ctx: dict) -> ToolOutput:
    name = safe_identifier(params.get("name", ""), "GodmodeAction")
    kw = dict(NAME=name, NAME_STR=lua_string(name))
    server = fill(REMOTE_SERVER, HEADER=HEADER.format(tool="tool:remote_event"), **kw)
    client = fill(REMOTE_CLIENT, HEADER=HEADER.format(tool="tool:remote_event"), **kw)
    return ToolOutput(
        summary=(f"A validated RemoteEvent system named `{name}`:\n\n"
                 "- **Server** (`ServerScriptService`): creates `ReplicatedStorage.Remotes." + name + "`, type-checks every "
                 "argument (`typeof`, NaN and range checks), allow-lists actions, rate limits per player "
                 "(8 calls/s) and clears state on `PlayerRemoving`.\n"
                 "- **Client** (`StarterPlayerScripts`): fires the remote on **E** with a client-side cooldown "
                 "(cosmetic only; the server limit is the real one).\n\nPut your game logic in `handleAction`."),
        actions=[
            create_script("ServerScriptService", f"{name}Server", "Script", server, f"Server handler for {name}"),
            create_script("StarterPlayer.StarterPlayerScripts", f"{name}Client", "LocalScript", client,
                          f"Client caller for {name}"),
        ])


