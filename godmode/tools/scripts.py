LEADERSTATS = """{{HEADER}}-- Creates leaderstats for every player. Only server scripts may change these values.
local Players = game:GetService("Players")

local STATS = {
{{STAT_LINES}}}

local function setupLeaderstats(player: Player)
	if player:FindFirstChild("leaderstats") then
		return
	end
	local folder = Instance.new("Folder")
	folder.Name = "leaderstats"
	for _, stat in ipairs(STATS) do
		local value = Instance.new("IntValue")
		value.Name = stat.name
		value.Value = stat.default
		value.Parent = folder
	end
	folder.Parent = player
end

Players.PlayerAdded:Connect(setupLeaderstats)
for _, player in ipairs(Players:GetPlayers()) do
	task.spawn(setupLeaderstats, player)
end
"""

STAT_WORDS = ("coins", "cash", "money", "gems", "points", "kills", "deaths", "wins", "level", "xp", "stage", "score")


def _stat_names(message: str, default: tuple[str, ...]) -> list[str]:
    m = message.lower()
    names = [w.capitalize() if w != "xp" else "XP" for w in STAT_WORDS if re.search(rf"\b{w}\b", m)]
    return names or list(default)


def leaderstats(params: dict, ctx: dict) -> ToolOutput:
    stats = _stat_names(ctx.get("message", ""), ("Coins",))
    lines = "".join(f"\t{{ name = {lua_string(s)}, default = 0 }},\n" for s in stats)
    src = fill(LEADERSTATS, HEADER=HEADER.format(tool="tool:leaderstats"), STAT_LINES=lines)
    return ToolOutput(
        summary=f"Leaderstats with {', '.join(f'`{s}`' for s in stats)} (IntValues) created on the server for every "
                "player, including players who joined before the script ran.",
        actions=[create_script("ServerScriptService", "Leaderstats", "Script", src, "Leaderstats setup")])


