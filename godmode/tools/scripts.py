NPC_SCRIPT = """{{HEADER}}-- Patrols every NPC model tagged "GodmodePatrolNPC" through the parts in Workspace.{{FOLDER}}.
local CollectionService = game:GetService("CollectionService")
local PathfindingService = game:GetService("PathfindingService")

local TAG = "GodmodePatrolNPC"
local WAYPOINT_FOLDER = workspace:WaitForChild({{FOLDER_STR}})
local MOVE_TIMEOUT = 6
local PAUSE_AT_POINT = {{PAUSE}}
local active = {}

local function sortedPoints()
	local points = {}
	for _, child in ipairs(WAYPOINT_FOLDER:GetChildren()) do
		if child:IsA("BasePart") then
			table.insert(points, child)
		end
	end
	table.sort(points, function(a, b)
		return a.Name < b.Name
	end)
	return points
end

local function moveTo(humanoid: Humanoid, position: Vector3): boolean
	local finished = false
	local reached = false
	local connection = humanoid.MoveToFinished:Connect(function(success)
		reached = success
		finished = true
	end)
	humanoid:MoveTo(position)
	local started = os.clock()
	while not finished and os.clock() - started < MOVE_TIMEOUT do
		task.wait(0.1)
	end
	connection:Disconnect()
	return reached
end

local function followPath(npc: Model, humanoid: Humanoid, root: BasePart, target: Vector3)
	local path = PathfindingService:CreatePath({ AgentRadius = 2, AgentHeight = 5, AgentCanJump = true })
	local ok = pcall(function()
		path:ComputeAsync(root.Position, target)
	end)
	if not ok or path.Status ~= Enum.PathStatus.Success then
		moveTo(humanoid, target)
		return
	end
	for _, waypoint in ipairs(path:GetWaypoints()) do
		if active[npc] ~= true or humanoid.Health <= 0 then
			return
		end
		if waypoint.Action == Enum.PathWaypointAction.Jump then
			humanoid.Jump = true
		end
		if not moveTo(humanoid, waypoint.Position) then
			return
		end
	end
end

local function patrol(npc: Instance)
	if not npc:IsA("Model") or active[npc] then
		return
	end
	local humanoid = npc:FindFirstChildOfClass("Humanoid")
	local root = npc:FindFirstChild("HumanoidRootPart")
	if humanoid == nil or root == nil or not root:IsA("BasePart") then
		warn("GodmodePatrolNPC needs a Humanoid and HumanoidRootPart: " .. npc:GetFullName())
		return
	end
	active[npc] = true
	pcall(function()
		root:SetNetworkOwner(nil)
	end)
	local diedConnection = humanoid.Died:Connect(function()
		active[npc] = nil
	end)
	task.spawn(function()
		while active[npc] == true and npc.Parent ~= nil do
			local points = sortedPoints()
			if #points == 0 then
				task.wait(1)
			end
			for _, point in ipairs(points) do
				if active[npc] ~= true then
					break
				end
				followPath(npc, humanoid, root, point.Position)
				task.wait(PAUSE_AT_POINT)
			end
		end
		diedConnection:Disconnect()
		active[npc] = nil
	end)
end

CollectionService:GetInstanceAddedSignal(TAG):Connect(patrol)
CollectionService:GetInstanceRemovedSignal(TAG):Connect(function(npc)
	active[npc] = nil
end)
for _, npc in ipairs(CollectionService:GetTagged(TAG)) do
	patrol(npc)
end
"""


def npc_patrol(params: dict, ctx: dict) -> ToolOutput:
    n = max(2, min(int(params.get("count", 4)), 20)) if params.get("count_noun", "").startswith(("waypoint", "point")) else 4
    spacing = max(8.0, min(float(params.get("spacing", params.get("size", 30))), 200.0))
    folder_name = "GodmodePatrolPoints"
    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n
        pts.append(part(f"Point{i + 1:02d}", (2, 1, 2), (spacing * math.cos(a), 0.5, spacing * math.sin(a)),
                        (255, 170, 0), "Neon", CanCollide=False, Transparency=0.5, CanQuery=False, CanTouch=False))
    tree = node("Folder", folder_name, {}, pts)
    src = fill(NPC_SCRIPT, HEADER=HEADER.format(tool="tool:npc_patrol"), FOLDER=folder_name,
               FOLDER_STR=lua_string(folder_name), PAUSE=1)
    return ToolOutput(
        summary=(f"An NPC patrol system: {n} waypoint parts in `Workspace.{folder_name}` (visited in name order) and a "
                 "server Script using `PathfindingService` (with jump waypoints, a move timeout and a direct-MoveTo fallback). "
                 "It drives every Model tagged **`GodmodePatrolNPC`**, stops when the NPC dies or is removed, and sets "
                 "server network ownership so exploiters cannot steer it.\n\n"
                 "**You still need to:** add an R15 rig (Avatar > Rig Builder) and give it the tag `GodmodePatrolNPC` "
                 "(Properties > Tags)."),
        actions=[create_instances("Workspace", tree, "Create patrol waypoints"),
                 create_script("ServerScriptService", "GodmodeNPCPatrol", "Script", src, "NPC patrol controller")])


