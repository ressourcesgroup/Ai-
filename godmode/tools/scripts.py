DATASTORE = """{{HEADER}}-- Session-locked player data with retries, UpdateAsync and BindToClose.
-- Requires Game Settings > Security > Enable Studio Access to API Services (for Studio testing).
local Players = game:GetService("Players")
local DataStoreService = game:GetService("DataStoreService")
local RunService = game:GetService("RunService")

local STORE_NAME = "PlayerData_v1"
local KEY_PREFIX = "player_"
local SCHEMA_VERSION = 1
local MAX_RETRIES = 5
local LOCK_EXPIRE_SECONDS = 1800
local AUTOSAVE_INTERVAL = 120
local DEFAULTS = {
{{DEFAULT_LINES}}}

local store = DataStoreService:GetDataStore(STORE_NAME)
local profiles = {}
local saving = {}

local function newProfile()
	local data = { version = SCHEMA_VERSION, stats = {} }
	for name, value in pairs(DEFAULTS) do
		data.stats[name] = value
	end
	return data
end

local function retry(label: string, callback: () -> any): (boolean, any)
	local lastError = nil
	for attempt = 1, MAX_RETRIES do
		local ok, result = pcall(callback)
		if ok then
			return true, result
		end
		lastError = result
		warn(("[Data] %s failed (attempt %d/%d): %s"):format(label, attempt, MAX_RETRIES, tostring(result)))
		task.wait(math.min(2 ^ attempt, 16))
	end
	return false, lastError
end

local function sanitize(data: any)
	if typeof(data) ~= "table" then
		return newProfile()
	end
	if typeof(data.stats) ~= "table" then
		data.stats = {}
	end
	for name, value in pairs(DEFAULTS) do
		if typeof(data.stats[name]) ~= "number" then
			data.stats[name] = value
		end
	end
	data.version = SCHEMA_VERSION
	return data
end

local function loadProfile(player: Player)
	local key = KEY_PREFIX .. player.UserId
	for _ = 1, 3 do
		local lockedElsewhere = false
		local ok, result = retry("load " .. key, function()
			return store:UpdateAsync(key, function(old)
				local data = sanitize(old)
				local lock = data.lock
				if typeof(lock) == "table" and lock.jobId ~= game.JobId and os.time() - (lock.time or 0) < LOCK_EXPIRE_SECONDS then
					lockedElsewhere = true
					return nil
				end
				lockedElsewhere = false
				data.lock = { jobId = game.JobId, time = os.time() }
				return data
			end)
		end)
		if ok and not lockedElsewhere and result ~= nil then
			return sanitize(result)
		end
		task.wait(5)
	end
	return nil
end

local function writeStatsToProfile(player: Player, profile)
	local leaderstats = player:FindFirstChild("leaderstats")
	if leaderstats == nil then
		return
	end
	for name in pairs(DEFAULTS) do
		local valueObject = leaderstats:FindFirstChild(name)
		if valueObject and valueObject:IsA("IntValue") then
			profile.stats[name] = valueObject.Value
		end
	end
end

local function saveProfile(player: Player, release: boolean)
	local profile = profiles[player]
	if profile == nil or saving[player] then
		return
	end
	saving[player] = true
	writeStatsToProfile(player, profile)
	local key = KEY_PREFIX .. player.UserId
	retry("save " .. key, function()
		return store:UpdateAsync(key, function(old)
			local current = sanitize(old)
			local lock = current.lock
			if typeof(lock) == "table" and lock.jobId ~= game.JobId then
				return nil
			end
			current.stats = profile.stats
			if release then
				current.lock = nil
			else
				current.lock = { jobId = game.JobId, time = os.time() }
			end
			return current
		end)
	end)
	saving[player] = nil
end

local function onPlayerAdded(player: Player)
	local profile = loadProfile(player)
	if profile == nil then
		player:Kick("Your data could not be loaded safely. Please rejoin.")
		return
	end
	if not player:IsDescendantOf(Players) then
		profiles[player] = profile
		saveProfile(player, true)
		profiles[player] = nil
		return
	end
	profiles[player] = profile
	local folder = player:FindFirstChild("leaderstats")
	if folder == nil then
		folder = Instance.new("Folder")
		folder.Name = "leaderstats"
		folder.Parent = player
	end
	for name, value in pairs(profile.stats) do
		local valueObject = folder:FindFirstChild(name)
		if valueObject == nil then
			valueObject = Instance.new("IntValue")
			valueObject.Name = name
			valueObject.Parent = folder
		end
		valueObject.Value = value
	end
end

local function onPlayerRemoving(player: Player)
	saveProfile(player, true)
	profiles[player] = nil
end

Players.PlayerAdded:Connect(onPlayerAdded)
Players.PlayerRemoving:Connect(onPlayerRemoving)
for _, player in ipairs(Players:GetPlayers()) do
	task.spawn(onPlayerAdded, player)
end

task.spawn(function()
	while true do
		task.wait(AUTOSAVE_INTERVAL)
		for player in pairs(profiles) do
			task.spawn(saveProfile, player, false)
		end
	end
end)

game:BindToClose(function()
	local pending = 0
	for player in pairs(profiles) do
		pending += 1
		task.spawn(function()
			saveProfile(player, true)
			pending -= 1
		end)
	end
	local started = os.clock()
	while pending > 0 and os.clock() - started < 25 do
		task.wait(0.1)
	end
	if RunService:IsStudio() then
		task.wait(1)
	end
end)
"""


def datastore(params: dict, ctx: dict) -> ToolOutput:
    stats = _stat_names(ctx.get("message", ""), ("Coins",))
    lines = "".join(f"\t{s} = 0,\n" for s in stats)
    src = fill(DATASTORE, HEADER=HEADER.format(tool="tool:datastore"), DEFAULT_LINES=lines)
    return ToolOutput(
        summary=("A DataStore save system for " + ", ".join(f"`{s}`" for s in stats) + ":\n\n"
                 "- `UpdateAsync` only (no blind `SetAsync`), with a **session lock** (JobId + timestamp, expires after "
                 "30 min) so two servers never overwrite each other.\n"
                 "- Every call is wrapped in `pcall` with exponential-backoff retries.\n"
                 "- Autosave every 120 s, save + unlock on `PlayerRemoving`, and `BindToClose` waits (max 25 s) for all saves.\n"
                 "- Values are mirrored into `leaderstats` IntValues; schema-versioned and sanitized on load."),
        warnings=["To test in Studio enable Game Settings > Security > 'Enable Studio Access to API Services'."],
        actions=[create_script("ServerScriptService", "PlayerData", "Script", src, "DataStore save system")])


