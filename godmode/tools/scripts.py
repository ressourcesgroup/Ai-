DOOR_SCRIPT = """{{HEADER}}-- Server-side sliding door: a ProximityPrompt opens it with a tween, then it auto-closes.
local TweenService = game:GetService("TweenService")

local model = script.Parent
local door = model:WaitForChild("Door")
local prompt = door:WaitForChild("OpenPrompt")

local OPEN_TIME = {{DURATION}}
local STAY_OPEN = 3
local closedCFrame = door.CFrame
local openCFrame = closedCFrame + Vector3.new(0, door.Size.Y - 0.5, 0)
local tweenInfo = TweenInfo.new(OPEN_TIME, Enum.EasingStyle.Quad, Enum.EasingDirection.InOut)
local busy = false

local function tweenTo(target: CFrame)
	local tween = TweenService:Create(door, tweenInfo, { CFrame = target })
	tween:Play()
	tween.Completed:Wait()
	tween:Destroy()
end

prompt.Triggered:Connect(function(player: Player)
	if busy then
		return
	end
	local character = player.Character
	local root = character and character:FindFirstChild("HumanoidRootPart")
	if root == nil or (root.Position - door.Position).Magnitude > prompt.MaxActivationDistance + 5 then
		return
	end
	busy = true
	prompt.Enabled = false
	tweenTo(openCFrame)
	task.wait(STAY_OPEN)
	tweenTo(closedCFrame)
	prompt.Enabled = true
	busy = false
end)
"""


def tween_door(params: dict, ctx: dict) -> ToolOutput:
    w = max(4.0, min(float(params.get("width", params.get("size", 6))), 40.0))
    h = max(6.0, min(float(params.get("height", 10)), 40.0))
    color = params.get("rgb", (124, 92, 70))
    mat = params.get("material", "Wood")
    tree = node("Model", "GodmodeDoor", {}, [
        part("FrameLeft", (1, h + 1, 1), (-(w / 2 + 0.5), (h + 1) / 2, 0), (90, 90, 90), "Concrete"),
        part("FrameRight", (1, h + 1, 1), (w / 2 + 0.5, (h + 1) / 2, 0), (90, 90, 90), "Concrete"),
        part("FrameTop", (w + 2, 1, 1), (0, h + 1.5, 0), (90, 90, 90), "Concrete"),
        {**part("Door", (w, h, 0.6), (0, h / 2, 0), color, mat),
         "children": [node("ProximityPrompt", "OpenPrompt", {"ActionText": "Open", "ObjectText": "Door",
                                                            "MaxActivationDistance": 10, "HoldDuration": 0})]},
    ])
    dur = max(0.2, min(float(params.get("duration", 1)), 5.0))
    src = fill(DOOR_SCRIPT, HEADER=HEADER.format(tool="tool:tween_door"), DURATION=dur)
    return ToolOutput(
        summary=(f"A {w:g}x{h:g} sliding door model with a ProximityPrompt. A server Script tweens it open ({dur:g} s, "
                 "Quad InOut), keeps it open 3 s, and closes it; it ignores triggers while moving and re-checks the "
                 "player's distance on the server."),
        actions=[create_instances("Workspace", tree, "Create door model"),
                 create_script("Workspace.GodmodeDoor", "DoorController", "Script", src, "Door tween controller")])


PLATFORM_SCRIPT = """{{HEADER}}-- Moves the platform back and forth forever with TweenService (server-side, replicates to everyone).
local TweenService = game:GetService("TweenService")

local platform = script.Parent:WaitForChild("Platform")
local TRAVEL = Vector3.new({{TRAVEL}})
local DURATION = {{DURATION}}

local tween = TweenService:Create(
	platform,
	TweenInfo.new(DURATION, Enum.EasingStyle.Sine, Enum.EasingDirection.InOut, -1, true, 0.5),
	{ CFrame = platform.CFrame + TRAVEL }
)
tween:Play()

script.Destroying:Connect(function()
	tween:Cancel()
	tween:Destroy()
end)
"""


def moving_platform(params: dict, ctx: dict) -> ToolOutput:
    dist = max(4.0, min(float(params.get("spacing", params.get("size", 20))), 200.0))
    vertical = bool(re.search(r"\b(up|down|vertical|elevator|lift)\b", ctx.get("message", "").lower()))
    travel = "0, %g, 0" % dist if vertical else "%g, 0, 0" % dist
    dur = max(0.5, min(float(params.get("duration", 3)), 30.0))
    tree = node("Model", "GodmodeMovingPlatform", {}, [
        part("Platform", (10, 1, 10), (0, 10, 0), params.get("rgb", (13, 105, 172)), params.get("material", "Metal"))])
    src = fill(PLATFORM_SCRIPT, HEADER=HEADER.format(tool="tool:moving_platform"), TRAVEL=travel, DURATION=dur)
    return ToolOutput(
        summary=(f"A moving platform that travels {dist:g} studs {'vertically' if vertical else 'sideways'} and back "
                 f"every {dur:g} s (Sine InOut, infinite, reversing)."),
        warnings=["Tweening an anchored part's CFrame does not carry standing players along; for rideable platforms "
                  "use an unanchored part with AlignPosition/PrismaticConstraint."],
        actions=[create_instances("Workspace", tree, "Create moving platform"),
                 create_script("Workspace.GodmodeMovingPlatform", "PlatformMover", "Script", src, "Platform tween")])
