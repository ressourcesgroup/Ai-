"""Luau source generator: play a GODMODE animation on the local character.

The generated LocalScript (for StarterPlayer.StarterCharacterScripts) loads the
animation through the Humanoid's Animator, toggles it with a key, and destroys
the AnimationTrack / Animation and unbinds input when the character dies or the
script is removed. If no published asset id is filled in it falls back, in
Studio only, to KeyframeSequenceProvider:RegisterKeyframeSequence on the
KeyframeSequence created by the plugin.
"""

from __future__ import annotations

import re

TEMPLATE = """-- Generated by GODMODE tool:animation (deterministic template, verified by godmode.luau; not neural-model output)
-- Plays the "{{NAME}}" animation ({{STYLE}}) on this character. Press {{KEY}} to toggle.
-- Publish the KeyframeSequence (Animation Editor > Publish to Roblox) and paste the id below for live games.
local ContextActionService = game:GetService("ContextActionService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local RunService = game:GetService("RunService")

local ANIMATION_ID = "rbxassetid://0"
local SEQUENCE_FOLDER = {{FOLDER}}
local SEQUENCE_NAME = {{NAME_STR}}
local ACTION_NAME = "Godmode_{{NAME}}"
local TOGGLE_KEY = Enum.KeyCode.{{KEY}}
local LOOPED = {{LOOPED}}
local FADE_TIME = 0.15

local character = script.Parent
local humanoid = character:WaitForChild("Humanoid")
local animator = humanoid:WaitForChild("Animator")

local animation = nil
local track = nil
local connections = {}

local function resolveAnimationId(): string?
	if ANIMATION_ID ~= "rbxassetid://0" then
		return ANIMATION_ID
	end
	if not RunService:IsStudio() then
		return nil
	end
	local folder = ReplicatedStorage:FindFirstChild(SEQUENCE_FOLDER)
	local sequence = folder and folder:FindFirstChild(SEQUENCE_NAME)
	if sequence == nil or not sequence:IsA("KeyframeSequence") then
		return nil
	end
	local ok, temporaryId = pcall(function()
		return game:GetService("KeyframeSequenceProvider"):RegisterKeyframeSequence(sequence)
	end)
	if ok then
		return temporaryId
	end
	return nil
end

local function cleanup()
	ContextActionService:UnbindAction(ACTION_NAME)
	for _, connection in ipairs(connections) do
		connection:Disconnect()
	end
	table.clear(connections)
	if track then
		track:Stop(FADE_TIME)
		track:Destroy()
		track = nil
	end
	if animation then
		animation:Destroy()
		animation = nil
	end
end

local animationId = resolveAnimationId()
if animationId == nil then
	warn("[GODMODE] No animation id for " .. SEQUENCE_NAME .. ": publish it and set ANIMATION_ID.")
else
	animation = Instance.new("Animation")
	animation.AnimationId = animationId
	track = animator:LoadAnimation(animation)
	track.Priority = Enum.AnimationPriority.{{PRIORITY}}
	track.Looped = LOOPED

	ContextActionService:BindAction(ACTION_NAME, function(_, inputState)
		if inputState ~= Enum.UserInputState.Begin or track == nil then
			return Enum.ContextActionResult.Pass
		end
		if track.IsPlaying then
			track:Stop(FADE_TIME)
		else
			track:Play(FADE_TIME)
		end
		return Enum.ContextActionResult.Sink
	end, true, TOGGLE_KEY)

	table.insert(connections, humanoid.Died:Connect(cleanup))
	table.insert(connections, script.Destroying:Connect(cleanup))
end
"""

_KEYS = {chr(c) for c in range(ord("A"), ord("Z") + 1)}


def player_script(anim_name: str, style: str, looped: bool, priority: str = "Action", key: str = "G",
                  folder: str = "GodmodeAnimations") -> str:
    name = re.sub(r"[^A-Za-z0-9_]", "", anim_name) or "GodmodeAnimation"
    key = key.upper() if key.upper() in _KEYS else "G"
    folder = re.sub(r"[^A-Za-z0-9_]", "", folder) or "GodmodeAnimations"
    out = TEMPLATE
    for k, v in {"NAME": name, "NAME_STR": f'"{name}"', "STYLE": re.sub(r"[^a-z]", "", style), "KEY": key,
                 "LOOPED": "true" if looped else "false", "PRIORITY": priority, "FOLDER": f'"{folder}"'}.items():
        out = out.replace("{{" + k + "}}", v)
    return out
