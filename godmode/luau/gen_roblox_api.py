"""Generate ``roblox_api.lua``: the Roblox class/enum database used by ``roblox_mock.lua``.

Input is Roblox's own API dump (``Full-API-Dump.json`` as mirrored by
MaximumADHD/Roblox-Client-Tracker). Treat it as untrusted data: it is only parsed
with ``json`` and every string copied into the Lua output is validated or quoted.

Only what a *plugin* can touch is kept:
  * members tagged NotScriptable are dropped;
  * a member is kept only when its (read) security is None or PluginSecurity;
    a property whose write security is stricter is marked read-only.

Run:
    python3 -I godmode/luau/gen_roblox_api.py path/to/Full-API-Dump.json [version]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).with_name("roblox_api.lua")
PLUGIN_VISIBLE = {"None", "PluginSecurity"}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SAFE_DEFAULT = re.compile(r"^[A-Za-z0-9 _.,{}\-]{0,64}$")


def _q(text: str) -> str:
    """A Lua string literal (ASCII only; anything else is escaped as \\ddd)."""
    out = []
    for ch in text:
        o = ord(ch)
        if ch in "\\\"":
            out.append("\\" + ch)
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            for b in ch.encode("utf-8"):
                out.append(f"\\{b:03d}")
    return '"' + "".join(out) + '"'


def _type_code(vt: dict) -> str | None:
    cat, name = vt.get("Category"), vt.get("Name")
    prefix = {"Primitive": "", "DataType": "D:", "Enum": "E:", "Class": "C:"}.get(cat)
    if prefix is None or not isinstance(name, str) or not IDENT.match(name):
        return None
    return prefix + name


def _security(sec) -> tuple[str, str]:
    if isinstance(sec, dict):
        return str(sec.get("Read")), str(sec.get("Write"))
    return str(sec), str(sec)


def build(dump: dict) -> dict:
    classes = {}
    for cls in dump["Classes"]:
        name = cls["Name"]
        if not IDENT.match(name):
            continue
        tags = [t for t in cls.get("Tags") or [] if isinstance(t, str)]
        entry = {"super": cls.get("Superclass") if cls.get("Superclass") != "<<<ROOT>>>" else None,
                 "tags": tags, "props": {}, "funcs": [], "events": [], "callbacks": []}
        for m in cls.get("Members", []):
            mname = m.get("Name")
            if not isinstance(mname, str) or not IDENT.match(mname):
                continue
            mtags = m.get("Tags") or []
            if "NotScriptable" in mtags:
                continue
            read, write = _security(m.get("Security"))
            if read not in PLUGIN_VISIBLE:
                continue
            kind = m.get("MemberType")
            if kind == "Property":
                code = _type_code(m.get("ValueType") or {})
                if code is None:
                    continue
                flags = ""
                if "ReadOnly" in mtags or write not in PLUGIN_VISIBLE:
                    flags += "r"
                if "Deprecated" in mtags:
                    flags += "d"
                default = m.get("Default")
                if not isinstance(default, str) or default.startswith("__api_dump") or not SAFE_DEFAULT.match(default):
                    default = None
                entry["props"][mname] = (code, flags, default)
            elif kind == "Function":
                entry["funcs"].append(mname + ("!" if "Deprecated" in mtags else ""))
            elif kind == "Event":
                entry["events"].append(mname + ("!" if "Deprecated" in mtags else ""))
            elif kind == "Callback":
                entry["callbacks"].append(mname)
        classes[name] = entry
    enums = {}
    for enum in dump["Enums"]:
        if not IDENT.match(enum["Name"]):
            continue
        items = {}
        for item in enum.get("Items", []):
            if isinstance(item.get("Name"), str) and IDENT.match(item["Name"]) and isinstance(item.get("Value"), int):
                items[item["Name"]] = item["Value"]
        enums[enum["Name"]] = items
    return {"classes": classes, "enums": enums}


def render(db: dict, version: str) -> str:
    lines = [
        "-- GENERATED by godmode/luau/gen_roblox_api.py from Roblox's API dump -- do not edit.",
        f"-- Roblox version {version}. Plugin-visible members only (None/PluginSecurity, scriptable).",
        "-- props: name = { type, flags (r = read-only, d = deprecated), default-or-nil }",
        "-- funcs/events: a trailing '!' marks a deprecated member.",
        "local C, E = {}, {}",
    ]
    for name in sorted(db["classes"]):
        c = db["classes"][name]
        props = ",".join(
            f"{p}={{{_q(code)},{_q(flags)}{',' + _q(d) if d is not None else ''}}}"
            for p, (code, flags, d) in sorted(c["props"].items())
        )
        funcs = ",".join(_q(f) for f in sorted(c["funcs"]))
        events = ",".join(_q(e) for e in sorted(c["events"]))
        cbs = ",".join(_q(e) for e in sorted(c["callbacks"]))
        sup = _q(c["super"]) if c["super"] else "nil"
        tags = ",".join(_q(t) for t in sorted(c["tags"]))
        lines.append(f"C.{name}={{super={sup},tags={{{tags}}},props={{{props}}},funcs={{{funcs}}},events={{{events}}},callbacks={{{cbs}}}}}")
    for name in sorted(db["enums"]):
        items = ",".join(f"{k}={v}" for k, v in sorted(db["enums"][name].items(), key=lambda kv: (kv[1], kv[0])))
        lines.append(f"E.{name}={{{items}}}")
    lines.append(f"return {{ version = {_q(version)}, classes = C, enums = E }}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> None:
    if len(argv) < 2:
        raise SystemExit(__doc__)
    path = Path(argv[1])
    dump = json.loads(path.read_text(encoding="utf-8"))
    version = argv[2] if len(argv) > 2 else str(dump.get("Version", "unknown"))
    if not re.match(r"^[0-9.]+$", version):
        raise SystemExit(f"unexpected version string: {version!r}")
    db = build(dump)
    OUT.write_text(render(db, version), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KB, {len(db['classes'])} classes, {len(db['enums'])} enums)")


if __name__ == "__main__":
    main(sys.argv)
